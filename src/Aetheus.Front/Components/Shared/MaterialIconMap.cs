    /// <summary>Every Material name the table knows, for the tests that prove the migration is complete.</summary>
    public static IReadOnlyCollection<string> Names => Map.Keys;

    /// <summary>The Phosphor icon that replaces <paramref name="material"/>; an unknown name is a bug, not a fallback.</summary>
    public static OmniIconName Resolve(string material) =>
        Map.TryGetValue(material, out var icon)
            ? icon
            : throw new ArgumentOutOfRangeException(nameof(material), material, "Material icon name missing from MaterialIconMap.");

    /// <summary>The icon of a page header (<c>OmniPageHeader.Icon</c>) named by <paramref name="material"/>;
    /// none when the name is blank, as the former Aetheus page header drew none then.</summary>
    public static RenderFragment? HeaderIcon(string? material) => string.IsNullOrWhiteSpace(material)
        ? null
        : builder =>
        {
            builder.OpenComponent<OmniIcon>(0);
            builder.AddComponentParameter(1, nameof(OmniIcon.Name), Resolve(material));
            builder.CloseComponent();
        };
}
