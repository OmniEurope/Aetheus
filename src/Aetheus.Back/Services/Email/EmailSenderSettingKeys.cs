namespace Aetheus.Back.Services.Email;

/// <summary>
/// Where the e-mail sender is stored: plain values in the platform settings table, passwords in the
/// platform secret store (AES-256 encrypted, never in plain text in the database or in Git).
/// </summary>
public static class EmailSenderSettingKeys
{
    /// <summary>Prefix of every setting below; the generic settings list hides these rows.</summary>
    public const string Prefix = "EmailSender:";

    public const string Mode = Prefix + "Mode";
    public const string Host = Prefix + "Host";
    public const string Port = Prefix + "Port";
    public const string TlsMode = Prefix + "TlsMode";
    public const string Username = Prefix + "Username";
    public const string FromAddress = Prefix + "FromAddress";

    /// <summary>Value of <see cref="Mode"/> that selects the custom SMTP server; anything else is the default.</summary>
    public const string CustomMode = "Custom";
    public const string DefaultMode = "Default";

    /// <summary>Secret holding the custom SMTP server's password.</summary>
    public const string SmtpPasswordSecret = Prefix + "SmtpPassword";

    /// <summary>Secret holding the password of one no-reply mailbox, generated by Aetheus.</summary>
    public static string NoReplyPasswordSecret(string address) =>
        Prefix + "NoReply:" + address.ToLowerInvariant();

    /// <summary>The local part of the default sender's address.</summary>
    public const string NoReplyLocalPart = "no-reply";

    /// <summary>Submission port of the mail stack Aetheus sets up (mail-setup: STARTTLS mandatory, SMTP AUTH).</summary>
    public const int ManagedSubmissionPort = 587;
}
