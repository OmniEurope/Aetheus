using System.Security.Cryptography.X509Certificates;
using Aetheus.Back.Middleware;
using Microsoft.AspNetCore.DataProtection;

namespace Aetheus.Back.Extensions;

/// <summary>Host wiring read by <c>Program.cs</c> at startup: file logging, Data Protection, the
/// PostgreSQL context, CORS origins and the database initialization run before the first request.</summary>
internal static class StartupHostingExtensions
{
    /// <summary>JSON file logging. The sink writes synchronously under a single lock, so its level
    /// drives throughput under load. It does NOT bind appsettings "Logging" - set it explicitly:
    /// Warning in Production (steady-state = silent, no per-request disk I/O contention), Information
    /// in dev. Override via Logging:FileLog:MinLevel.</summary>
    public static void AddAetheusFileLogging(this WebApplicationBuilder builder)
    {
        var logDirectory = builder.Configuration["Logging:FileLog:Directory"]
            ?? Path.Combine(AppContext.BaseDirectory, "logs");
        Directory.CreateDirectory(logDirectory);
        var fileLogLevel = Enum.TryParse<LogLevel>(
            builder.Configuration["Logging:FileLog:MinLevel"], ignoreCase: true, out var lvl)
                ? lvl
                : builder.Environment.IsProduction() ? LogLevel.Warning : LogLevel.Information;
        builder.Logging.AddProvider(new JsonFileLoggerProvider(
            logDirectory,
            fileLogLevel,
            instance: builder.Configuration["Logging:FileLog:Instance"] ?? Environment.MachineName));
    }

    /// <summary>Persists keys to a known directory so cookie/token protectors survive container
    /// restarts, and encrypts them at rest with the self-signed certificate generated by the
    /// entrypoint script when it exists (silences "No XML encryptor configured").</summary>
    public static void AddAetheusDataProtection(this WebApplicationBuilder builder)
    {
        var dpKeyPath = builder.Configuration["DataProtection:KeyPath"]
            ?? (builder.Environment.IsDevelopment()
                ? Path.Combine(AppContext.BaseDirectory, "dp-keys")
                : "/app/data/dp-keys");
        Directory.CreateDirectory(dpKeyPath);
        var dpBuilder = builder.Services.AddDataProtection()
            .PersistKeysToFileSystem(new DirectoryInfo(dpKeyPath))
            .SetApplicationName("Aetheus");
        var dpCertPath = Path.Combine(dpKeyPath, "dp-cert.pfx");
        if (File.Exists(dpCertPath))
        {
            var dpCert = X509CertificateLoader.LoadPkcs12FromFile(dpCertPath, password: null);
            dpBuilder.ProtectKeysWithCertificate(dpCert);
        }
    }

    /// <summary>The PostgreSQL application context (PostgreSQL only).</summary>
    public static void AddAetheusDatabase(this WebApplicationBuilder builder)
    {
        var connectionString = builder.Configuration.GetConnectionString("Default");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            throw new InvalidOperationException(
                "ConnectionStrings:Default is not configured. Aetheus requires a PostgreSQL connection string. " +
                "For local development, run the dev database via 'docker compose -f deploy/compose/dev-db.compose.yml up -d' " +
                "and set ConnectionStrings:Default in appsettings.Development.json or via environment variable.");
        }
        // The E2E schema reset (/api/dev/reset-db, Development only) closes this gate; the interceptor that
        // holds the other commands back while it is closed is only added in Development.
        builder.Services.AddSingleton<Aetheus.Back.Components.Dev.SchemaResetGate>();
        builder.Services.AddSingleton<Aetheus.Back.Components.Dev.SchemaResetInterceptor>();
        var addSchemaResetInterceptor = builder.Environment.IsDevelopment();
        builder.Services.AddDbContext<AppDbContext>((services, options) =>
        {
            if (addSchemaResetInterceptor)
                options.AddInterceptors(services.GetRequiredService<Aetheus.Back.Components.Dev.SchemaResetInterceptor>());
            options.UseNpgsql(connectionString)
                .ConfigureWarnings(w => w.Ignore(
                    Microsoft.EntityFrameworkCore.Diagnostics.RelationalEventId.PendingModelChangesWarning,
                    // Retired-server query filters intentionally hide dependents through required
                    // relationships. Paths requiring retired data opt out through
                    // ServerQueryFilters.ExcludeRetired.
                    Microsoft.EntityFrameworkCore.Diagnostics.CoreEventId.PossibleIncorrectRequiredNavigationWithQueryFilterInteractionWarning));
        });
    }

    /// <summary>The allowed CORS origins: the local front-end in Development, then Cors:FrontendUrl,
    /// then every non-empty Cors:Origins entry, in that order (duplicates kept, the policy dedupes).</summary>
    public static List<string> ResolveCorsOrigins(this WebApplicationBuilder builder)
    {
        var corsOrigins = new List<string>();
        if (builder.Environment.IsDevelopment())
        {
            corsOrigins.Add(LocalDevelopmentEndpoints.FrontendHttpsOrigin);
            corsOrigins.Add(LocalDevelopmentEndpoints.FrontendHttpOrigin);
        }
        var frontendUrl = builder.Configuration["Cors:FrontendUrl"];
        if (!string.IsNullOrEmpty(frontendUrl))
            corsOrigins.Add(frontendUrl);
        corsOrigins.AddRange(builder.Configuration.GetSection("Cors:Origins").GetChildren()
            .Select(origin => origin.Value)
            .Where(value => !string.IsNullOrEmpty(value))
            .Select(value => value!));
        return corsOrigins;
    }

    /// <summary>Migrates (unless skipped), seeds, backfills the port registry and re-encrypts residual
    /// plaintext secrets, in that order, before the application serves its first request.</summary>
    public static async Task InitializeDatabaseAsync(this WebApplication app)
    {
        await using var scope = app.Services.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        var startupLogger = scope.ServiceProvider.GetRequiredService<ILoggerFactory>().CreateLogger("Startup");
        // MigrateAsync is relational-only; tests swap the provider to InMemory and would throw.
        if (db.Database.IsRelational())
            await ApplyMigrationsAsync(app.Configuration, db, startupLogger);

        await DbInitializer.SeedAsync(db, app.Configuration);
        await scope.ServiceProvider.GetRequiredService<TotoConformanceSeeder>().SeedAsync();
        await DemoDataStartupSeeder.SeedIfEnabledAsync(scope.ServiceProvider, db, app.Environment, app.Configuration);
        // Reconcile the canonical catalog last: optional demo seeders must not be able to
        // recreate active non-canonical templates after the legacy archival pass.
        await scope.ServiceProvider.GetRequiredService<DeliveryPipelineTemplateSeeder>().SeedAsync();

        // Populate the registry from existing port fields idempotently, preserving and reporting
        // conflicting reservations.
        await Aetheus.Back.Components.PortRegistry.IsolatedPortBackfill.RunAsync(
            db,
            scope.ServiceProvider.GetRequiredService<Aetheus.Back.Components.PortRegistry.IPortRegistryService>(),
            startupLogger);

        // Audit 360 lot A: one-shot, idempotent re-encryption of any residual plaintext webhook secrets
        // written before secrets were encrypted at rest. Lets WebhookService decrypt strictly afterwards.
        var encryptionService = scope.ServiceProvider.GetRequiredService<IEncryptionService>();
        await Aetheus.Back.Components.Webhooks.WebhookSecretReencryption.RunAsync(db, encryptionService, startupLogger);
        await Aetheus.Back.Components.Notifications.NotificationConfigurationReencryption.RunAsync(
            db, encryptionService, startupLogger);
    }

    /// <summary>S-TECH-58: guard against a parasitic instance (e.g. a second checkout/worktree pointed at
    /// the shared dev DB) applying divergent migrations. Setting Database:SkipMigrations=true (or
    /// AETHEUS_SKIP_MIGRATIONS=1) makes the instance attach read/write WITHOUT migrating - the
    /// canonical instance owns the schema. Defaults to migrating, so prod startup is unchanged.</summary>
    private static async Task ApplyMigrationsAsync(IConfiguration configuration, AppDbContext db, ILogger startupLogger)
    {
        var skipMigrations = configuration.GetValue("Database:SkipMigrations", false)
            || string.Equals(Environment.GetEnvironmentVariable("AETHEUS_SKIP_MIGRATIONS"), "1", StringComparison.Ordinal);
        if (skipMigrations)
        {
            // Blue-green replicas rely on the migration-only job to apply their schema before
            // startup.
            startupLogger.LogInformation(
                "Database:SkipMigrations is set: this instance does not apply EF migrations. The schema is " +
                "migrated by its owner (the blue-green migration job, or the canonical development instance).");
            return;
        }
        startupLogger.LogInformation("Applying EF migrations to database '{Database}'", db.Database.GetDbConnection().Database);
        await db.Database.MigrateAsync();
    }
}
