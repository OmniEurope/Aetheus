namespace Aetheus.Back.Components.PackageRegistry;

/// <summary>
/// The Maven 2 repository layout of the registry. Files are stored as deployed; the
/// <c>maven-metadata.xml</c> documents and every checksum are generated from the stored state, so what
/// a client reads is always consistent with what the registry holds.
/// </summary>
public interface IMavenRegistryService
{
    /// <summary>Handles an HTTP PUT of <c>mvn deploy</c>: a file is stored (immutable), a checksum is
    /// verified against the stored file, an uploaded <c>maven-metadata.xml</c> is checked for
    /// well-formedness and then replaced by the generated one.</summary>
    Task PutAsync(MavenRepositoryPath path, Stream content, string publishedBy, CancellationToken ct = default);

    /// <summary>The content served for a GET/HEAD, or null when nothing exists at that path.</summary>
    Task<MavenRepositoryContent?> GetAsync(MavenRepositoryPath path, CancellationToken ct = default);

    /// <summary>Opens a stored file named by <see cref="MavenRepositoryContent.StoragePath"/>.</summary>
    Stream? OpenStored(string storagePath);
}

/// <summary>Either generated bytes or a stored file, with its media type.</summary>
public sealed record MavenRepositoryContent(string ContentType, byte[]? Bytes, string? StoragePath);
